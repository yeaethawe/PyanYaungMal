def current_language():
    lang = getattr(g, "language", None)
    if lang in STRINGS:
        return lang
    try:
        sess = session.get("language")
    except RuntimeError:
        sess = None
    if sess in STRINGS:
        return sess
    return "en"


def t(key, **kwargs):
    lang = current_language()
    text = STRINGS[lang].get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
